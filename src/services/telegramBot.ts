// Storage Keys
const CONFIG_KEY = 'ny_telegram_config_v2';
const TEMPLATES_KEY = 'ny_telegram_templates_v2';
const LOGS_KEY = 'ny_telegram_logs_v2';

export function loadTelegramConfig(): TelegramConfig {
  try {
    const saved = localStorage.getItem(CONFIG_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      return {
        botToken: parsed.botToken || DEFAULT_BOT_TOKEN,
        channelId: parsed.channelId || '',
        channelTitle: parsed.channelTitle || '',
        channelUsername: parsed.channelUsername || '',
        isVerified: !!parsed.isVerified,
        autoBroadcast: !!parsed.autoBroadcast,
        sendStickers: parsed.sendStickers !== false,
        lastVerifiedAt: parsed.lastVerifiedAt || '',
      };
    }
  } catch {}
  return {
    botToken: DEFAULT_BOT_TOKEN,
    channelId: '',
    isVerified: false,
    autoBroadcast: false,
    sendStickers: true,
  };
}

export function saveTelegramConfig(config: TelegramConfig): void {
  try {
    localStorage.setItem(CONFIG_KEY, JSON.stringify(config));
  } catch {}
}

export function loadTelegramTemplates(): TelegramTemplates {
  try {
    const saved = localStorage.getItem(TEMPLATES_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      return { ...DEFAULT_TEMPLATES, ...parsed };
    }
  } catch {}
  return { ...DEFAULT_TEMPLATES };
}

export function saveTelegramTemplates(templates: TelegramTemplates): void {
  try {
    localStorage.setItem(TEMPLATES_KEY, JSON.stringify(templates));
  } catch {}
}

export function loadTelegramLogs(): TelegramLog[] {
  try {
    const saved = localStorage.getItem(LOGS_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed)) return parsed.slice(0, 50);
    }
  } catch {}
  return [];
}

export function appendTelegramLog(log: Omit<TelegramLog, 'id' | 'timestamp'>): TelegramLog {
  const newLog: TelegramLog = {
    ...log,
    id: `log-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`,
    timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' }),
  };

  try {
    const current = loadTelegramLogs();
    const updated = [newLog, ...current].slice(0, 50);
    localStorage.setItem(LOGS_KEY, JSON.stringify(updated));
  } catch {}

  return newLog;
}


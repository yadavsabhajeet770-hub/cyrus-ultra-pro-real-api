export async function verifyTelegramBotAndChannel(
  botToken: string,
  channelId: string
): Promise<{ success: boolean; message: string; chatTitle?: string; chatUsername?: string }> {
  const cleanToken = (botToken || '').trim();
  let cleanChatId = (channelId || '').trim();

  if (!cleanToken) {
    return { success: false, message: 'Bot Token is required!' };
  }

  if (!cleanChatId) {
    return { success: false, message: 'Channel ID / Username is required!' };
  }

  // Format channel ID if missing @ for public usernames
  if (!cleanChatId.startsWith('@') && !cleanChatId.startsWith('-') && !/^\d+$/.test(cleanChatId)) {
    cleanChatId = `@${cleanChatId}`;
  }

  try {
    // 1. Verify Bot Token validity first
    const getMeUrl = `https://api.telegram.org/bot${cleanToken}/getMe`;
    const meRes = await fetch(getMeUrl);
    const meData = await meRes.json();

    if (!meData.ok) {
      return {
        success: false,
        message: `Invalid Bot Token: ${meData.description || 'Check your token'}`,
      };
    }

    const botName = meData.result?.username || 'Bot';

    // 2. Verify Channel Chat & Admin Permissions
    const getChatUrl = `https://api.telegram.org/bot${cleanToken}/getChat?chat_id=${encodeURIComponent(cleanChatId)}`;
    const chatRes = await fetch(getChatUrl);
    const chatData = await chatRes.json();

    if (!chatData.ok) {
      return {
        success: false,
        message: `Channel Error (${chatData.error_code}): ${chatData.description}. Make sure @${botName} is added to this channel as an ADMINISTRATOR with Post Messages permission!`,
      };
    }

    const title = chatData.result?.title || chatData.result?.first_name || cleanChatId;
    const username = chatData.result?.username ? `@${chatData.result.username}` : cleanChatId;

    return {
      success: true,
      message: `Successfully connected to channel: "${title}" (${username})!`,
      chatTitle: title,
      chatUsername: username,
    };
  } catch (err: any) {
    return {
      success: false,
      message: `Network error connecting to Telegram: ${err.message || 'Check connection'}`,
    };
  }
}

export async function sendTelegramMessage(
  botToken: string,
  channelId: string,
  text: string
): Promise<{ success: boolean; messageId?: number; error?: string }> {
  const cleanToken = (botToken || '').trim();
  let cleanChatId = (channelId || '').trim();

  if (!cleanChatId.startsWith('@') && !cleanChatId.startsWith('-') && !/^\d+$/.test(cleanChatId)) {
    cleanChatId = `@${cleanChatId}`;
  }

  try {
    const url = `https://api.telegram.org/bot${cleanToken}/sendMessage`;
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        chat_id: cleanChatId,
        text,
        parse_mode: 'HTML',
        disable_web_page_preview: true,
      }),
    });

    const data = await res.json();
    if (data.ok) {
      return { success: true, messageId: data.result?.message_id };
    } else {
      return { success: false, error: data.description || 'Failed to send message' };
    }
  } catch (err: any) {
    return { success: false, error: err.message || 'Network error' };
  }
}


export async function broadcastStartSessionPipeline(
  config: TelegramConfig,
  templates: TelegramTemplates,
  serverName: string,
  currentPrediction: StrategyResult | null,
  targetPeriod: string
): Promise<{ success: boolean; error?: string }> {
  if (!config.channelId || !config.botToken) {
    return { success: false, error: 'Telegram Channel or Bot Token not configured.' };
  }

  try {
    // 1. Send Start Session Sticker (once)
    if (config.sendStickers) {
      await sendTelegramSticker(config.botToken, config.channelId, STICKERS.startSession);
      appendTelegramLog({
        type: 'STICKER',
        message: 'Sent Start Session Sticker 🚀',
        stickerId: STICKERS.startSession,
        status: 'SUCCESS',
      });
    }

    // 2. Send Start Session Message
    const startMsg = formatSessionStartMessage(templates.startSession, serverName);
    const startRes = await sendTelegramMessage(config.botToken, config.channelId, startMsg);
    appendTelegramLog({
      type: 'START',
      message: 'Started Prediction Broadcast Session',
      status: startRes.success ? 'SUCCESS' : 'FAILED',
      error: startRes.error,
    });

    // 3. Immediately send First Prediction Signal
    if (currentPrediction && targetPeriod) {
      await new Promise(resolve => setTimeout(resolve, 800));
      const predMsg = formatPredictionMessage(templates.prediction, targetPeriod, serverName, currentPrediction);
      const predRes = await sendTelegramMessage(config.botToken, config.channelId, predMsg);
      appendTelegramLog({
        type: 'PREDICTION',
        message: `Sent Initial Signal for Period ${targetPeriod}`,
        status: predRes.success ? 'SUCCESS' : 'FAILED',
        error: predRes.error,
      });
    }

    return { success: true };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Error during broadcast start' };
  }
}


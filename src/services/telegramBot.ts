export async function broadcastRoundResultPipeline(
  config: TelegramConfig,
  templates: TelegramTemplates,
  serverName: string,
  record: WingoHistoryRecord,
  streak: number,
  lossRun: number
): Promise<{ success: boolean; error?: string }> {
  if (!config.channelId || !config.botToken) {
    return { success: false, error: 'Telegram Channel or Bot Token not configured.' };
  }

  try {
    const resultStatus = record.result;

    if (resultStatus === 'JACKPOT') {
      // 1. Result text message
      const jackMsg = formatJackpotMessage(templates.jackpot, record, serverName);
      const resMsg = await sendTelegramMessage(config.botToken, config.channelId, jackMsg);
      appendTelegramLog({
        type: 'JACKPOT',
        message: `Jackpot Result for Period ${record.period}`,
        status: resMsg.success ? 'SUCCESS' : 'FAILED',
        error: resMsg.error,
      });

      // 2. Win / Jackpot sticker
      if (config.sendStickers) {
        await sendTelegramSticker(config.botToken, config.channelId, STICKERS.jackpot);
      }
    } else if (resultStatus === 'WIN') {
      // 1. Result text message
      const winMsg = formatWinMessage(templates.win, record, serverName, streak);
      const resMsg = await sendTelegramMessage(config.botToken, config.channelId, winMsg);
      appendTelegramLog({
        type: 'WIN',
        message: `Win Result for Period ${record.period}`,
        status: resMsg.success ? 'SUCCESS' : 'FAILED',
        error: resMsg.error,
      });

      // 2. Win sticker
      if (config.sendStickers) {
        await sendTelegramSticker(config.botToken, config.channelId, STICKERS.win);
      }
    } else if (resultStatus === 'LOSS') {
      // 1. Result text message
      const lossMsg = formatLossMessage(templates.loss, record, serverName, lossRun);
      const resMsg = await sendTelegramMessage(config.botToken, config.channelId, lossMsg);
      appendTelegramLog({
        type: 'LOSS',
        message: `Loss/Recovery Result for Period ${record.period}`,
        status: resMsg.success ? 'SUCCESS' : 'FAILED',
        error: resMsg.error,
      });

      // 2. Loss sticker
      if (config.sendStickers) {
        await sendTelegramSticker(config.botToken, config.channelId, STICKERS.loss);
      }
    }

    return { success: true };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Error broadcasting result' };
  }
}



export function formatSessionStopMessage(
  template: string,
  wins: number,
  losses: number
): string {
  const time = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
  const total = wins + losses;
  const winRate = total > 0 ? ((wins / total) * 100).toFixed(1) : '100.0';

  return template
    .replace(/{total_wins}/g, String(wins))
    .replace(/{total_loss}/g, String(losses))
    .replace(/{win_rate}/g, winRate)
    .replace(/{time}/g, time);
}


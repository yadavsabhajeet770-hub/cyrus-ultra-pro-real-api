export function formatPredictionMessage(
  template: string,
  period: string,
  serverName: string,
  prediction: StrategyResult
): string {
  const time = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
  const numsStr = Array.isArray(prediction.nums) && prediction.nums.length > 0
    ? prediction.nums.map(n => `[ ${n} ]`).join(' ')
    : '---';

  const predTarget = prediction.focusTarget || prediction.pred || 'BIG';
  const patternStr = prediction.databasePatternDisplay || prediction.detectedPatternName || 'SURESHOT';

  return template
    .replace(/{period}/g, period || '---')
    .replace(/{server}/g, serverName || 'SERVER 1 · CYRUS ENGINE')
    .replace(/{prediction}/g, predTarget)
    .replace(/{pattern}/g, patternStr)
    .replace(/{numbers}/g, numsStr)
    .replace(/{color}/g, prediction.colorPred || 'GREEN')
    .replace(/{confidence}/g, String(prediction.confidence || 95))
    .replace(/{time}/g, time);
}

export function formatWinMessage(
  template: string,
  record: WingoHistoryRecord,
  serverName: string,
  streak: number
): string {
  const time = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });
  return template
    .replace(/{period}/g, record.period || '---')
    .replace(/{actual_num}/g, String(record.actualNum ?? '-'))
    .replace(/{actual_size}/g, record.actualSize || '')
    .replace(/{actual_color}/g, record.actualColor || '')
    .replace(/{server}/g, serverName || 'SERVER 1 · CYRUS ENGINE')
    .replace(/{streak}/g, String(Math.max(1, streak)))
    .replace(/{time}/g, time);
}

